# Generate the GB2312 hanzi bitmap header for the table engine charset
# filter. The GB2312-80 charset is exactly the set of codepoints that can be
# encoded with Python's "gb2312" codec.
#
# Usage: python3 gen-gb2312table.py > gb2312table.h

import sys

START = 0x4E00
END = 0x9FFF


def main() -> int:
    size = END - START + 1
    bitmap = bytearray((size + 7) // 8)
    count = 0
    for cp in range(START, END + 1):
        try:
            chr(cp).encode("gb2312")
        except UnicodeEncodeError:
            continue
        bitmap[(cp - START) // 8] |= 1 << ((cp - START) % 8)
        count += 1

    lines = []
    for i in range(0, len(bitmap), 20):
        lines.append(", ".join(f"0x{v:02x}" for v in bitmap[i : i + 20]))

    print("/*")
    print(" * SPDX-FileCopyrightText: 2026 fcitx5-chinese-addons contributors")
    print(" *")
    print(" * SPDX-License-Identifier: LGPL-2.1-or-later")
    print(" *")
    print(" * Generated by gen-gb2312table.py. Do not edit manually.")
    print(" */")
    print("#ifndef _TABLE_GB2312TABLE_H_")
    print("#define _TABLE_GB2312TABLE_H_")
    print()
    print("#include <array>")
    print("#include <cstddef>")
    print("#include <cstdint>")
    print()
    print("namespace fcitx {")
    print()
    print("// Bitmap for the %d GB2312 hanzi within CJK Unified Ideographs block" % count)
    print("// (U+4E00 - U+9FFF).")
    print(f"inline constexpr size_t kGB2312BitmapStart = 0x{START:X};")
    print(f"inline constexpr size_t kGB2312BitmapEnd = 0x{END:X};")
    print(f"inline constexpr std::array<uint8_t, {len(bitmap)}> kGB2312Bitmap = {{")
    for line in lines:
        print(f"    {line},")
    print("};")
    print()
    print("// Check whether the codepoint within CJK Unified Ideographs block is")
    print("// included in GB2312 charset.")
    print("inline bool isGB2312Codepoint(uint32_t codepoint) {")
    print("    if (codepoint < kGB2312BitmapStart || codepoint > kGB2312BitmapEnd) {")
    print("        return false;")
    print("    }")
    print("    const size_t offset = codepoint - kGB2312BitmapStart;")
    print("    return kGB2312Bitmap[offset / 8] & (1U << (offset % 8));")
    print("}")
    print()
    print("} // namespace fcitx")
    print()
    print("#endif // _TABLE_GB2312TABLE_H_")
    return 0


if __name__ == "__main__":
    sys.exit(main())
